function guideTables() {
  const used = new Set();
  const swatch = (h) => { used.add(h); return `<span class="swatch sw-${h.slice(1)}"></span>`; };
  const families = Object.entries(tokens.palette).map(([family, steps]) => {
    const rows = Object.entries(steps).filter(([s]) => !s.startsWith('$')).map(([step, h]) => {
      const onPaper = contrast(h, hex('ink.50')), onInk = contrast(h, hex('ink.950'));
      return `        <tr><th scope="row">${swatch(h)}<code>--sp-${family}-${step}</code></th><td><code>${h}</code></td><td>${onPaper.toFixed(2)} to 1, ${level(onPaper)}</td><td>${onInk.toFixed(2)} to 1, ${level(onInk)}</td></tr>`;
    });
    const desc = steps.$description ? `\n    <p>${steps.$description}</p>` : '';
    return `    <h4>${family[0].toUpperCase()}${family.slice(1)}</h4>${desc}
    <table>
      <caption>${family[0].toUpperCase()}${family.slice(1)}: ${rows.length} shades, with contrast against paper and ink</caption>
      <thead><tr><th scope="col">Token</th><th scope="col">Hex</th><th scope="col">On paper (#FBFAF7)</th><th scope="col">On ink (#101430)</th></tr></thead>
      <tbody>
${rows.join('\n')}
      </tbody>
    </table>`;
  }).join('\n');

  const pairs = ['light', 'dark'].map((scheme) => {
    const rows = contrastRows.filter((r) => r.scheme === scheme).map((r) =>
      `        <tr><th scope="row">${r.purpose}</th><td><code>${r.fg}</code> on <code>${r.bg}</code></td><td>${swatch(r.f)}${r.f} on ${swatch(r.b)}${r.b}</td><td>${r.ratio.toFixed(2)} to 1</td><td>${r.ratio >= r.min ? 'Passed' : 'Failed'} (needs ${r.min} to 1)</td></tr>`);
    return `    <table>
      <caption>${scheme === 'light' ? 'Light' : 'Dark'} scheme: ${rows.length} colour pairs checked</caption>
      <thead><tr><th scope="col">Use</th><th scope="col">Tokens</th><th scope="col">Colours</th><th scope="col">Contrast</th><th scope="col">Result</th></tr></thead>
      <tbody>
${rows.join('\n')}
      </tbody>
    </table>`;
  }).join('\n');

  const brand = brandRows.map((r) =>
    `        <tr><th scope="row">${r.purpose}</th><td>${swatch(r.f)}${r.f} on ${swatch(r.b)}${r.b}</td><td>${r.ratio.toFixed(2)} to 1</td><td>${r.ratio >= r.min ? 'Passed' : 'Failed'} (needs ${r.min} to 1)</td></tr>`).join('\n');

  const swatchCss = `/* Generated by scripts/build.mjs. Do not edit. */\n${[...used].sort().map((h) => `.sw-${h.slice(1)} { background: ${h}; }`).join('\n')}\n`;
  return { swatchCss, families, pairs, brand: `    <table>
      <caption>Logo colours: ${brandRows.length} pairs checked</caption>
      <thead><tr><th scope="col">Part</th><th scope="col">Colours</th><th scope="col">Contrast</th><th scope="col">Result</th></tr></thead>
      <tbody>
${brand}
      </tbody>
    </table>` };
}

function injectGuide() {
  const path = 'guide/index.html';
  if (!existsSync(join(ROOT, path))) return;
  let html = read(path);
  const { swatchCss, ...t } = guideTables();
  t.social = socialGuide();
  t.sound = soundGuide();
  emit('guide/swatches.css', swatchCss);
  for (const [key, value] of Object.entries(t)) {
    const re = new RegExp(`(<!-- build:${key} -->)[\\s\\S]*?(<!-- /build:${key} -->)`);
    if (!re.test(html)) { failures.push(`Guide: the build:${key} marker is missing.`); continue; }
    html = html.replace(re, `$1\n${value}\n    $2`);
  }
  html = html.replace(/(<!-- build:icons -->)[\s\S]*?(<!-- \/build:icons -->)/, `$1\n${icons.map((f) => {
    const n = f.replace(/\.svg$/, '');
    const mirror = MIRRORED.test(n) ? ' icon-mirror' : '';
    return `        <li><svg class="icon${mirror}" aria-hidden="true" focusable="false"><use href="../icons/sprite.svg#sp-icon-${n}"/></svg><code>${n}</code></li>`;
  }).join('\n')}\n        $2`).replace(/(<span id="icon-count">)\d*(<\/span>)/, `$1${icons.length}$2`);
  emit(path, html);
}

