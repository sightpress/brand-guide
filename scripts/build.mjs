const SC = {
  from: hex('ink.950'), to: hex('iris.950'), headline: hex('ink.50'), subline: hex('iris.100'),
  accent: hex('lumen.400'), glow: hex('lumen.300'), sTop: hex('iris.600'), sBottom: hex('iris.800'),
};

/** Greedy wrap at `measure`, then narrow the measure while the line count holds (like text-wrap: balance). */
function wrap(key, size, measure) {
  const s = outlines.strings[key], k = size / 1000;
  const lay = (m) => {
    const lines = [];
    let cur = [], w = 0;
    for (const word of s.words) {
      let x = cur.length ? w + s.space : 0;
      if (cur.length && (x + word.advance) * k > m) { lines.push({ words: cur, width: w * k }); cur = []; x = 0; }
      cur.push({ word, x });
      w = x + word.advance;
    }
    lines.push({ words: cur, width: w * k });
    return lines;
  };
  let best = lay(measure);
  for (let m = measure - 8; m > measure * 0.5; m -= 8) {
    const next = lay(m);
    if (next.length !== best.length || next.some((l) => l.width > m)) break;
    best = next;
  }
  return { lines: best, k, s };
}

function drawLines({ lines, k, s }, x, firstBaseline, leading, fill) {
  return lines.map((line, i) => `<g transform="translate(${x} ${+(firstBaseline + i * leading).toFixed(2)}) scale(${k})">${line.words.map(({ word, x: wx }) =>
    `<path transform="translate(${wx} 0)" fill="${fill}" d="${word.d}"/>${word.accent ? `<path transform="translate(${wx} 0)" fill="${SC.accent}" d="${word.accent}"/>` : ''}`).join('')}</g>`).join('\n  ');
}

function socialImage(img) {
  const { width: W, height: H } = img;
  const problems = [];
  if (img.avatar) {
    return { svg: `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" width="${W}" height="${H}">${markGroup({ square: true, scale: 0.8 })}</svg>`, problems };
  }
  const [x0, y0, x1, y1] = img.safe;
  const [b0, b1] = img.band ?? [0, H];

  // Text block: logo, headline, subline, centred vertically in the safe area.
  const head = wrap(img['headline-string'] ?? 'headline', img.headline, img.measure);
  const sub = wrap(img['subline-string'], img.subline, img.measure);
  const logoScale = img.logo / LOCKUP.mark, logoW = lockupWidth() * logoScale;
  const hLead = img.headline * 1.08, sLead = img.subline * 1.45;
  const hCap = head.s.capHeight * head.k, sCap = sub.s.capHeight * sub.k;
  const gap1 = img.logo * 0.62, gap2 = img.headline * 0.5;
  const hBlock = hCap + (head.lines.length - 1) * hLead + img.headline * 0.24;
  const sBlock = sCap + (sub.lines.length - 1) * sLead + img.subline * 0.24;
  const total = img.logo + gap1 + hBlock + gap2 + sBlock;
  const top = y0 + (y1 - y0 - total) / 2;
  const textW = Math.max(logoW, ...head.lines.map((l) => l.width), ...sub.lines.map((l) => l.width));
  if (total > y1 - y0) problems.push(`the text is ${Math.ceil(total)} pixels tall but the safe area is ${y1 - y0}`);
  if (x0 + textW > x1) problems.push(`the text is ${Math.ceil(textW)} pixels wide but the safe area is ${x1 - x0}`);

  // Decoration: the S of the mark drawn large at the inline end, with the dot glowing.
  const bandH = b1 - b0, ds = (bandH * 1.15) / 49, cx = img.decorX ?? W - bandH * 0.32, cy = (b0 + b1) / 2;
  const tx = cx - 31.75 * ds, ty = cy - 34 * ds;
  const dot = { x: tx + DOT.cx * ds, y: ty + DOT.cy * ds, r: DOT.r * ds };
  const glowR = dot.r * 3.2;
  const decorStart = Math.min(tx + 15 * ds, dot.x - glowR);
  if (x0 + textW + 24 > decorStart) problems.push(`the text runs into the decoration (it ends at ${Math.ceil(x0 + textW)} pixels, the decoration starts at ${Math.floor(decorStart)})`);

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${SC.from}"/><stop offset="1" stop-color="${SC.to}"/></linearGradient>
    <linearGradient id="s" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="${SC.sTop}"/><stop offset="1" stop-color="${SC.sBottom}"/></linearGradient>
    <radialGradient id="glow"><stop offset="0" stop-color="${SC.glow}" stop-opacity="0.3"/><stop offset="1" stop-color="${SC.glow}" stop-opacity="0"/></radialGradient>
  </defs>
  <rect width="${W}" height="${H}" fill="url(#bg)"/>
  <circle cx="${+dot.x.toFixed(1)}" cy="${+dot.y.toFixed(1)}" r="${+glowR.toFixed(1)}" fill="url(#glow)"/>
  <g transform="translate(${+tx.toFixed(2)} ${+ty.toFixed(2)}) scale(${+ds.toFixed(4)})">
    <path d="${S_PATH}" fill="none" stroke="url(#s)" stroke-width="7" stroke-linecap="round"/>
    <circle cx="${DOT.cx}" cy="${DOT.cy}" r="${DOT.r}" fill="${SC.accent}"/>
  </g>
  <g transform="translate(${x0} ${+top.toFixed(2)}) scale(${+logoScale.toFixed(4)})">
    <g transform="scale(${LOCKUP.mark / 64})">${markGroup()}</g>
    ${wordmark(LOCKUP.mark + LOCKUP.gap, 60 + LOCKUP.cap / 2, LOCKUP.cap, C.sightDark, C.pressDark)}
  </g>
  ${drawLines(head, x0, top + img.logo + gap1 + hCap, hLead, SC.headline)}
  ${drawLines(sub, x0, top + img.logo + gap1 + hBlock + gap2 + sCap, sLead, SC.subline)}
</svg>
`;
  return { svg, problems };
}

function checkAlt(img) {
  const drawn = img.avatar ? ['SightPress'] : ['SightPress', social.strings[img['headline-string'] ?? 'headline'].text, social.strings[img['subline-string']].text];
  const missing = drawn.filter((t) => !img.alt?.includes(t));
  return missing.map((t) => `the alt text does not include "${t}", which is drawn in the image`);
}

