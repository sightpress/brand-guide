/**
 * SightPress brand-guide build.
 *
 *   npm run build   check every rule, then regenerate the derived files
 *   npm run check   check every rule and that the derived files are up to date
 *                   (changes nothing; exits 1 on any failure, for CI)
 *
 * Sources (edit these):    tokens/tokens.json, logo/wordmark.json, icons/src/*.svg,
 *                          social/social.json, sound/sound.json
 * Generated (never edit):  tokens/tokens.css, logo/*.svg, favicons/*, icons/sprite.svg,
 *                          social/*.png, sound/*.wav, the tables and lists in guide/index.html
 *                          (social/outlines.json comes from scripts/outline-text.py)
 *
 * Output is plain text: "Passed" or "Failed" in words, no colour, no spinners.
 */
