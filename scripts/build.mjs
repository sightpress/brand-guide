  const problems = [];
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(name)) problems.push('the file name is not kebab-case');
  if (!svg.includes('viewBox="0 0 24 24"')) problems.push('the viewBox is not 0 0 24 24');
  if (!svg.includes('aria-hidden="true"')) problems.push('it is missing aria-hidden="true"');
  if (!svg.includes('stroke-width="2"')) problems.push('the stroke width is not 2');
