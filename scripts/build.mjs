function markGroup({ tile = C.tile, s = C.s, dot = C.dot, square = false, scale = 1 } = {}) {
  const t = scale === 1 ? '' : ` transform="translate(${32 - 32 * scale} ${32 - 32 * scale}) scale(${scale})"`;
  return `<rect width="64" height="64"${square ? '' : ' rx="16"'} fill="${tile}"/>
  <g${t}>
    <path d="${S_PATH}" fill="none" stroke="${s}" stroke-width="7" stroke-linecap="round"/>
    <circle cx="${DOT.cx}" cy="${DOT.cy}" r="${DOT.r}" fill="${dot}"/>
  </g>`;
}

function monoMark(id) {
  // One colour (currentColor); the S and the dot are cut out of the tile.
  return `<mask id="${id}">
    <rect width="64" height="64" rx="16" fill="#fff"/>
    <path d="${S_PATH}" fill="none" stroke="#000" stroke-width="7" stroke-linecap="round"/>
    <circle cx="${DOT.cx}" cy="${DOT.cy}" r="${DOT.r}" fill="#000"/>
  </mask>
  <rect width="64" height="64" rx="16" fill="currentColor" mask="url(#${id})"/>`;
}

const svgOpen = (w, h, extra = '') =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}" role="img" aria-label="SightPress"${extra}>\n  <title>SightPress</title>\n  `;

const wm = JSON.parse(read('logo/wordmark.json'));

function wordmark(x, baseline, cap, sight, press) {
  const k = cap / wm.capHeight;
  return `<g transform="translate(${x} ${baseline}) scale(${+k.toFixed(4)})">
    <path fill="${sight}" d="${wm.Sight}"/>
    <path fill="${press}" d="${wm.Press}"/>
  </g>`;
}

// Horizontal lockup geometry: mark 120 high; cap height 56, caps centred on the mark.
const LOCKUP = { mark: 120, gap: 30, cap: 56 };
const lockupWidth = () => Math.ceil(LOCKUP.mark + LOCKUP.gap + wm.width * (LOCKUP.cap / wm.capHeight) + 4);

function lockup({ sight, press, mono = false }) {
  const { mark, gap, cap } = LOCKUP, baseline = 60 + cap / 2;
  const w = lockupWidth();
  const m = mono ? `<g transform="scale(${mark / 64})">${monoMark('sp-logo-knockout')}</g>`
    : `<g transform="scale(${mark / 64})">\n  ${markGroup()}\n  </g>`;
  return `${svgOpen(w, mark, mono ? ' fill="currentColor"' : '')}${m}\n  ${wordmark(mark + gap, baseline, cap, sight, press)}\n</svg>\n`;
}

function stacked({ sight, press }) {
  const mark = 128, cap = 48, k = cap / wm.capHeight, textW = wm.width * k;
  const w = Math.ceil(Math.max(mark, textW) + 8), h = mark + 32 + cap + 24;
  const mx = (w - mark) / 2, tx = (w - textW) / 2;
  return `${svgOpen(w, h)}<g transform="translate(${+mx.toFixed(2)} 0) scale(${mark / 64})">\n  ${markGroup()}\n  </g>\n  ${wordmark(+tx.toFixed(2), mark + 32 + cap, cap, sight, press)}\n</svg>\n`;
}

