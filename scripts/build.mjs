/* ------------------------------------------------------------------ colour */

function hex(ref) {
  if (ref.startsWith('#')) return ref.toUpperCase();
  const [family, step] = ref.split('.');
  const value = tokens.palette[family]?.[step];
  if (!value) throw new Error(`Unknown palette colour "${ref}".`);
  return value.toUpperCase();
}

function luminance(h) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255)
    .map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

const level = (ratio) => (ratio >= 7 ? 'AAA' : ratio >= 4.5 ? 'AA' : ratio >= 3 ? 'AA large text and non-text' : 'Fails');

const contrastRows = [];
for (const scheme of ['light', 'dark']) {
  for (const [fg, bg, min, purpose] of tokens.contrast.pairs) {
    const f = hex(tokens.color[scheme][fg]);
    const b = hex(tokens.color[scheme][bg]);
    const ratio = contrast(f, b);
    contrastRows.push({ scheme, fg, bg, f, b, ratio, min, purpose });
    if (ratio < min) failures.push(`Contrast (${scheme}): ${purpose}, ${fg} on ${bg}, is ${ratio.toFixed(2)} to 1; it needs at least ${min} to 1.`);
  }
}
const brandRows = tokens.contrast.brand.map(([fg, bg, min, purpose]) => {
  const ratio = contrast(hex(fg), hex(bg));
  if (ratio < min) failures.push(`Contrast (brand): ${purpose} is ${ratio.toFixed(2)} to 1; it needs at least ${min} to 1.`);
  return { fg, bg, f: hex(fg), b: hex(bg), ratio, min, purpose };
});

/* ------------------------------------------------------------------ output */

function emit(path, content) {
  const full = join(ROOT, path);
  const current = existsSync(full) ? readFileSync(full) : null;
  const next = Buffer.isBuffer(content) ? content : Buffer.from(content);
  if (current && current.equals(next)) return;
  if (CHECK_ONLY) { stale.push(path); return; }
  mkdirSync(dirname(full), { recursive: true });
  writeFileSync(full, next);
  written++;
}

/* --------------------------------------------------------------- tokens.css */

function cssTokens() {
  const out = [];
  const head = '/* Generated by scripts/build.mjs from tokens/tokens.json. Do not edit. */\n';
  const palette = [];
  for (const [family, steps] of Object.entries(tokens.palette)) {
    for (const [step, value] of Object.entries(steps)) {
      if (!step.startsWith('$')) palette.push(`  --sp-${family}-${step}: ${value};`);
    }
  }
  const scheme = (name) => Object.entries(tokens.color[name])
    .map(([k, v]) => `  --sp-color-${k}: var(--sp-${v.replace('.', '-')});`).join('\n');

  const f = tokens.font;
  const scripts = Object.entries(f['script-fallbacks']).filter(([k]) => !k.startsWith('$')).map(([, v]) => v).join(', ');
  const stack = (s) => s.replace(/, (serif|sans-serif|monospace)$/, `, ${scripts}, $1`);
  const scale = Object.entries(f.size).filter(([k]) => !k.startsWith('$'))
    .map(([k, v]) => `  --sp-font-size-${k.replace('-', 'n')}: ${v};`).join('\n');
  const group = (prefix, obj) => Object.entries(obj).filter(([k]) => !k.startsWith('$'))
    .map(([k, v]) => `  --sp-${prefix}-${k}: ${v};`).join('\n');

  out.push(`${head}
:root {
  color-scheme: light dark;

  /* Palette */
${palette.join('\n')}

  /* Type */
  --sp-font-display: ${stack(f.display)};
  --sp-font-text: ${stack(f.text)};
  --sp-font-mono: ${stack(f.mono)};
${group('font-weight', f.weight)}
${scale}
${group('line-height', f['line-height'])}
  --sp-measure: ${f.measure};

  /* Space, shape, depth, motion */
${group('space', tokens.space)}
${group('radius', tokens.radius)}
${group('shadow', tokens.shadow)}
  --sp-focus-width: ${tokens.focus.width};
  --sp-focus-offset: ${tokens.focus.offset};
  --sp-target-min: ${tokens.target.min};
${group('motion', tokens.motion)}

  /* Semantic colours: light (default) */
${scheme('light')}
}

/* Dark: follows the system unless the page sets data-color-scheme. */
@media (prefers-color-scheme: dark) {
  :root:not([data-color-scheme="light"]) {
    color-scheme: dark;
${scheme('dark').replace(/^/gm, '  ')}
  }
}
:root[data-color-scheme="dark"] {
  color-scheme: dark;
${scheme('dark')}
}
:root[data-color-scheme="light"] { color-scheme: light; }

/* More contrast: muted text and borders become full-strength. */
@media (prefers-contrast: more) {
  :root {
    --sp-color-text-muted: var(--sp-color-text);
    --sp-color-border: var(--sp-color-border-strong);
    --sp-color-border-strong: var(--sp-color-text);
  }
}

/* Windows High Contrast and other forced colours: let the system palette win. */
@media (forced-colors: active) {
  :root { --sp-color-focus: Highlight; --sp-color-focus-halo: Canvas; }
}

/* Motion off: transitions become instant. */
@media (prefers-reduced-motion: reduce) {
  :root { --sp-motion-fast: 0ms; --sp-motion-base: 0ms; }
}
`);
  return out.join('');
}

