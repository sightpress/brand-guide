#!/usr/bin/env python3
"""Outline the text drawn in the social images.

The images must never depend on an installed font, so every string in
social/social.json -> "strings" is shaped with HarfBuzz (kerning, ligatures)
and drawn to SVG path data, one entry per word so the build can wrap lines.
Re-run this whenever a string or a font in social.json changes:

    python3 -m venv .venv && .venv/bin/pip install fonttools uharfbuzz
    .venv/bin/python scripts/outline-text.py > social/outlines.json

Units: 1 em = 1000, baseline at y = 0, y pointing down (SVG).
"""
import json
import sys
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
EM = 1000


def num(v: float) -> str:
    return f"{v:.1f}".rstrip("0").rstrip(".")


class Face:
    def __init__(self, spec: dict):
        data = (ROOT / spec["file"]).read_bytes()
        self.axes = spec.get("axes", {})
        self.tracking = spec.get("tracking", 0)
        self.tt = TTFont(ROOT / spec["file"])
        self.upm = self.tt["head"].unitsPerEm
        self.scale = EM / self.upm
        self.glyphs = self.tt.getGlyphSet(location=self.axes) if self.axes else self.tt.getGlyphSet()
        self.order = self.tt.getGlyphOrder()
        self.hb = hb.Font(hb.Face(data))
        if self.axes:
            self.hb.set_variations(self.axes)
        os2 = self.tt["OS/2"]
        self.cap = os2.sCapHeight * self.scale
        self.ascender = os2.sTypoAscender * self.scale
        self.descender = -os2.sTypoDescender * self.scale

    def shape(self, word: str, accent: str = "") -> dict:
        """Shape one word. A trailing `accent` (such as ".") is drawn separately."""
        split = len(word) - len(accent) if accent and word.endswith(accent) else len(word)
        buf = hb.Buffer()
        buf.add_str(word)
        buf.guess_segment_properties()
        hb.shape(self.hb, buf, {"kern": True, "liga": True})
        pen = SVGPathPen(self.glyphs, ntos=num)
        accent_pen = SVGPathPen(self.glyphs, ntos=num)
        x = 0.0
        for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
            name = self.order[info.codepoint]
            s = self.scale
            target = accent_pen if info.cluster >= split else pen
            tpen = TransformPen(target, (s, 0, 0, -s, x + pos.x_offset * s, -pos.y_offset * s))
            self.glyphs[name].draw(tpen)
            x += pos.x_advance * s + self.tracking * EM
        shaped = {"d": pen.getCommands(), "advance": round(x - self.tracking * EM, 1)}
        if accent_pen.getCommands():
            shaped["accent"] = accent_pen.getCommands()
        return shaped


def main() -> None:
    source = json.loads((ROOT / "social/social.json").read_text("utf8"))
    faces = {k: Face(v) for k, v in source["fonts"].items() if not k.startswith("$")}
    out = {"$description": "Generated by scripts/outline-text.py from social/social.json. Do not edit.", "strings": {}}
    for key, spec in source["strings"].items():
        if key.startswith("$"):
            continue
        face = faces[spec["font"]]
        out["strings"][key] = {
            "text": spec["text"],
            "font": spec["font"],
            "accent": spec.get("accent", ""),
            "space": round(face.shape(" ")["advance"], 1),
            "capHeight": round(face.cap, 1),
            "ascender": round(face.ascender, 1),
            "descender": round(face.descender, 1),
            "words": [face.shape(w, spec.get("accent", "")) for w in spec["text"].split(" ")],
        }
    # Copied so the build can tell when the outlines are out of date.
    out["fonts"] = source["fonts"]
    json.dump(out, sys.stdout, indent=1, ensure_ascii=False)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
