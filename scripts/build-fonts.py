#!/usr/bin/env python3
"""Build the self-hosted WOFF2 subsets in fonts/ from the OFL sources in fonts/src/.

    python3 -m venv .venv && .venv/bin/pip install fonttools brotli
    .venv/bin/python scripts/build-fonts.py

Each Latin family is split into "latin" and "latin-ext" files with matching
unicode-range values in fonts/fonts.css, so a page only downloads what it uses
(at most 2 files per script, the PLAN.md section 3.6 budget). Variable weight
axes are kept; Fraunces is pinned to SOFT=50, WONK=0 (the brand cut).

The brand fonts have no Arabic or Hebrew, so each role gets a companion family
covering only that script (for the he-IL and ar-SA launch locales):

    role     Arabic              Hebrew
    text     Noto Sans Arabic    Noto Sans Hebrew
    display  Noto Naskh Arabic   Frank Ruhl Libre

Their unicode-range holds only their own script, so Latin pages never download
them. Arabic and Hebrew have no true italics, so the upright file is also
declared as the italic face: browsers then never draw a fake slant. Their
weight axes are cut to 400-700, the weights the tokens use, which halves the
Arabic file.
"""
from io import BytesIO
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / "fonts" / "src", ROOT / "fonts"

RANGES = {
    "latin": "U+0000-00FF, U+0131, U+0152-0153, U+02BB-02BC, U+02C6, U+02DA, U+02DC, "
             "U+0304, U+0308, U+0329, U+2000-206F, U+20AC, U+2122, U+2191, U+2193, U+2212, U+2215, U+FEFF, U+FFFD",
    "latin-ext": "U+0100-02BA, U+02BD-02C5, U+02C7-02CC, U+02CE-02D7, U+02DD-02FF, U+0304, U+0308, "
                 "U+0329, U+1D00-1DBF, U+1E00-1E9F, U+1EF2-1EFF, U+2020, U+20A0-20AB, U+20AD-20C0, U+2113, U+2C60-2C7F, U+A720-A7FF",
    "arabic": "U+0600-06FF, U+0750-077F, U+0870-088E, U+0890-0891, U+0897-08E1, U+08E3-08FF, U+200C-200E, U+2010-2011, "
              "U+204F, U+2E41, U+FB50-FDFF, U+FE70-FE74, U+FE76-FEFC",
    "hebrew": "U+0307-0308, U+0590-05FF, U+200C-2010, U+20AA, U+25CC, U+FB1D-FB4F",
}

LATIN = ("latin", "latin-ext")

FAMILIES = [
    # (css family, source file, output stem, styles, weight range, pinned axes, ranges)
    ("Atkinson Hyperlegible Next", "AtkinsonHyperlegibleNext[wght].ttf", "atkinson-hyperlegible-next", ["normal"], "200 800", None, LATIN),
    ("Atkinson Hyperlegible Next", "AtkinsonHyperlegibleNext-Italic[wght].ttf", "atkinson-hyperlegible-next-italic", ["italic"], "200 800", None, LATIN),
    ("Atkinson Hyperlegible Mono", "AtkinsonHyperlegibleMono[wght].ttf", "atkinson-hyperlegible-mono", ["normal"], "200 800", None, LATIN),
    ("Fraunces", "Fraunces[SOFT,WONK,opsz,wght].ttf", "fraunces", ["normal"], "100 900", {"SOFT": 50, "WONK": 0}, LATIN),
    ("Fraunces", "Fraunces-Italic[SOFT,WONK,opsz,wght].ttf", "fraunces-italic", ["italic"], "100 900", {"SOFT": 50, "WONK": 0}, LATIN),
    # Script companions: upright only, also declared as italic (see the docstring).
    ("Noto Sans Arabic", "NotoSansArabic[wdth,wght].ttf", "noto-sans-arabic", ["normal", "italic"], "400 700", {"wdth": 100, "wght": (400, 700)}, ("arabic",)),
    ("Noto Naskh Arabic", "NotoNaskhArabic[wght].ttf", "noto-naskh-arabic", ["normal", "italic"], "400 700", None, ("arabic",)),
    ("Noto Sans Hebrew", "NotoSansHebrew[wdth,wght].ttf", "noto-sans-hebrew", ["normal", "italic"], "400 700", {"wdth": 100, "wght": (400, 700)}, ("hebrew",)),
    ("Frank Ruhl Libre", "FrankRuhlLibre[wght].ttf", "frank-ruhl-libre", ["normal", "italic"], "400 700", {"wght": (400, 700)}, ("hebrew",)),
]


def unicodes(spec: str) -> list[int]:
    cps = []
    for part in spec.split(","):
        part = part.strip().removeprefix("U+")
        lo, _, hi = part.partition("-")
        cps.extend(range(int(lo, 16), int(hi or lo, 16) + 1))
    return cps


def main() -> None:
    css = ["/* Generated by scripts/build-fonts.py. Fonts: SIL Open Font License 1.1, see fonts/OFL-*.txt. */\n"]
    for family, src, stem, styles, weights, pin, ranges in FAMILIES:
        for rng in ranges:
            spec = RANGES[rng]
            font = TTFont(SRC / src)
            if pin:
                # Round-trip through bytes so the subsetter sees a fully built font.
                buf = BytesIO()
                instantiateVariableFont(font, pin).save(buf)
                buf.seek(0)
                font = TTFont(buf)
            opts = subset.Options()
            opts.flavor = "woff2"
            opts.layout_features = ["*"]
            opts.name_IDs = ["*"]
            opts.notdef_outline = True
            sub = subset.Subsetter(opts)
            sub.populate(unicodes=unicodes(spec))
            sub.subset(font)
            name = f"{stem}-{rng}.woff2"
            font.flavor = "woff2"
            font.save(OUT / name)
            print(f"Wrote fonts/{name}, {(OUT / name).stat().st_size // 1024} KB.")
            for style in styles:
                css.append(
                    f"@font-face {{\n  font-family: \"{family}\";\n  font-style: {style};\n  font-weight: {weights};\n"
                    f"  font-display: swap;\n  src: url(\"{name}\") format(\"woff2\");\n  unicode-range: {spec};\n}}\n"
                )
    (OUT / "fonts.css").write_text("\n".join(css))
    print("Wrote fonts/fonts.css.")


if __name__ == "__main__":
    main()
